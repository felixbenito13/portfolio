"""Writes the Netlify _redirects file at the project root.

Run from anywhere:  python3 tools/redirects.py   (also runs with `npm run build` in tools/)

Fixed rules come first. Then one rule per page inside design-notes/, so an address at the
site root that matches a Design Notes page (for example /turn-off-the-ai.html) goes to
/design-notes/ with a 301. New posts are covered the next time this runs.
Rules without "!" only apply when no file exists at that address, so real pages are never hidden.
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

FIXED = [
    ('/breakdown-01-amazon-homepage.html', '/design-notes/breakdown-01-amazon-homepage.html', '301'),
    ('/where-creativity-comes-from.html', '/design-notes/where-creativity-comes-from.html', '301'),
    ('/alignment-happens-before-the-file-opens.html', '/design-notes/alignment-happens-before-the-file-opens.html', '301'),
    ('/design-notes/breakdown-03-younger-self.html', '/design-notes/', '301'),
    ('/portfolio', '/#work', '301'),
    ('/index.html', '/', '301!'),
]


def main():
    fixed_from = {f for f, _, _ in FIXED}
    pages = sorted(f for f in os.listdir(os.path.join(ROOT, 'design-notes'))
                   if f.endswith('.html') and f != 'index.html')
    root_files = set(os.listdir(ROOT))
    w = max(len(f) for f, _, _ in FIXED) + 2
    lines = ['# Generated by tools/redirects.py. Edit that file, not this one.', '',
             '# Fixed redirects']
    lines += ['%s %s %s' % (f.ljust(w), t, c) for f, t, c in FIXED]
    lines += ['', '# Design Notes pages requested at the site root']
    for f in pages:
        src = '/' + f
        if src in fixed_from or f in root_files:
            continue  # a real root page with that name wins
        lines.append('%s /design-notes/%s 301' % (src.ljust(w), f))
    open(os.path.join(ROOT, '_redirects'), 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
    print('wrote _redirects with %d rules' % sum(1 for l in lines if l.startswith('/')))


main()
